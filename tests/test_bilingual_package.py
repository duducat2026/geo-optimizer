class TestLayoutMapping:
    def test_report_and_schema_arcnames(self):
        assert layout.arcname_for(layout.REPORT_MD_ZH) == "zh/geo_analysis_report.md"
        assert layout.arcname_for(layout.REPORT_MD_EN) == "en/geo_analysis_report.md"
        assert layout.arcname_for(layout.REPORT_PDF_EN) == "en/geo_analysis_report.pdf"
        assert layout.arcname_for(layout.SCHEMA_EN) == "en/schema.jsonld.html"
        assert layout.report_arcnames("en") == ("en/geo_analysis_report.md",
                                                "en/geo_analysis_report.pdf")
        assert layout.report_arcnames("zh") == ("zh/geo_analysis_report.md",
                                                "zh/geo_analysis_report.pdf")

    def test_plan_items_and_platform_drafts(self):
        assert layout.arcname_for(f"plan_items/{ITEM_STEM}.md") == \
            f"zh/plan_items/{ITEM_STEM}.md"
        assert layout.arcname_for(f"plan_items/{ITEM_STEM}.en.md") == \
            f"en/plan_items/{ITEM_STEM}.md"
        # 平台稿只进其目标平台语言侧
        assert layout.arcname_for("zhihu_example.md") == "zh/zhihu_example.md"
        assert layout.arcname_for("medium_example.md") == "en/medium_example.md"
        # 语言中性文件留在根目录
        assert layout.arcname_for("page_snapshot.json") == "page_snapshot.json"
        assert layout.arcname_for("example_authority.md") == "example_authority.md"

    def test_artifact_arcname_uses_catalog_lang(self):
        assert layout.artifact_arcname("zhihu_article", "zhihu_article.md") == \
            "zh/artifacts/zhihu_article.md"
        assert layout.artifact_arcname("medium_article_en", "medium_article_en.md") == \
            "en/artifacts/medium_article_en.md"
        # 规则类产出物语言中性，不带语言目录前缀
        assert layout.artifact_arcname("sitemap_xml", "sitemap.xml") == \
            "artifacts/sitemap.xml"

    def test_split_faq(self):
        zh_text, en_text = layout.split_faq(FAQ_MD)
        assert "Sample answer" in en_text and not CJK_RE.search(en_text)
        assert en_text.startswith("# FAQ (English)")
        assert "English" not in zh_text and zh_text.startswith("# FAQ")
        assert "示例回答" in zh_text

    def test_split_faq_without_marker(self):
        zh_text, en_text = layout.split_faq("# FAQ\n\n只有中文")
        assert en_text == "" and "只有中文" in zh_text


class TestBilingualSplit:
    def test_split_by_marker(self):
        zh, en = generator.split_bilingual(
            "# 中文标题\n\n正文\n\n===EN===\n\n# English\n\nBody")
        assert zh.strip().endswith("正文") and en.strip() == "# English\n\nBody"

    def test_split_by_english_heading(self):
        zh, en = generator.split_bilingual(
            "# 中文标题\n\n正文\n\n## English Part\n\nBody")
        assert "English Part" in en and "## English" not in zh

    def test_pure_chinese_yields_no_english(self):
        zh, en = generator.split_bilingual("# 中文标题\n\n只有中文")
        assert en == "" and zh.startswith("# 中文标题")

    def test_marker_line_variants(self):
        for marker in ("===EN===", "== EN ==", "===EN==", "=EN="):
            zh, en = generator.split_bilingual(f"中文\n{marker}\nEnglish")
            assert (zh.strip(), en.strip()) == ("中文", "English"), marker

    def test_llm_without_english_part_backfills_template(self, app, monkeypatch):
        """模型漏掉英文段时用模板英文稿补齐，保证包内 en/ 不混入中文。"""
        monkeypatch.setattr(generator, "_make_client", lambda cfg: (object(), "m"))
        monkeypatch.setattr(generator, "_llm_generate",
                            lambda client, model, spec, ctx: "# 创建 Sitemap\n\n中文步骤")
        with app.app_context():
            admin = User.query.filter_by(username="admin").first()
            db.session.add(EvalTask(id="bi-llm", user_id=admin.id,
                                     target_url="https://example.com",
                                     overall_score=30.0))
            db.session.commit()
            items = generator.generate_for_task(
                "bi-llm", {"llm": {"api_key": "k", "base_url": "b"}},
                {"overall_score": 30.0})
            rows = [(i.source, i.content, i.content_en or "") for i in items]

        assert all(r[0] == "llm" for r in rows)
        assert all(CJK_RE.search(r[1]) for r in rows)
        assert all(r[2].strip() and not CJK_RE.search(r[2]) for r in rows)


