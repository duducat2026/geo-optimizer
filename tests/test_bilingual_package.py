class TestSchemaByLang:
    @staticmethod
    def _faqs():
        from geo_optimizer.web.faq_generator import FAQ

        return [
            FAQ("示例问题？", "示例回答。", "zh-CN", ["示例"], ["豆包"]),
            FAQ("Sample question?", "Sample answer.", "en-US", ["sample"], ["Perplexity"]),
        ]

    @staticmethod
    def _page():
        from geo_optimizer.models import CrawledPage

        return CrawledPage(url="https://example.com", title="Example", html="",
                           text="Article content here. " * 20, language="en",
                           meta_desc="Example site", meta_keywords="example",
                           headings=[(1, "Example"), (2, "Sub")], links=[],
                           word_count=500)

    def test_faqpage_filtered_by_language(self):
        from geo_optimizer.web.schema_generator import SchemaGenerator

        gen = SchemaGenerator()
        cfg = {"target": {"url": "https://example.com"}}

        en = gen.generate(self._page(), self._faqs(), cfg, lang="en")
        assert en["FAQPage"]["inLanguage"] == "en-US"
        assert en["FAQPage"]["mainEntity"][0]["name"] == "Sample question?"

        zh = gen.generate(self._page(), self._faqs(), cfg, lang="zh")
        assert zh["FAQPage"]["inLanguage"] == "zh-CN"
        assert zh["FAQPage"]["mainEntity"][0]["name"] == "示例问题？"

    def test_no_english_faq_skips_faqpage(self):
        from geo_optimizer.web.schema_generator import SchemaGenerator

        schemas = SchemaGenerator().generate(
            self._page(), self._faqs()[:1], {"target": {}}, lang="en")
        assert "FAQPage" not in schemas
        assert "WebPage" in schemas


def _fill_artifact_dir(base) -> str:
    """按 runner 落盘规则铺一个典型任务产物目录（扁平）。"""
    from pathlib import Path

    artifact_dir = Path(base)
    items_dir = artifact_dir / "plan_items"
    items_dir.mkdir(parents=True, exist_ok=True)
    for lang in layout.LANGS:
        md_name, pdf_name = layout.report_names(lang)
        (artifact_dir / md_name).write_text(
            report_builder.build_markdown(SAMPLE_RESULT, lang=lang), encoding="utf-8")
        (artifact_dir / pdf_name).write_bytes(b"%PDF-1.4 fake")
        (artifact_dir / layout.schema_name(lang)).write_text(
            "<script type=\"application/ld+json\">{}</script>", encoding="utf-8")
        (items_dir / layout.plan_item_name(ITEM_STEM, lang)).write_text(
            f"action item body ({lang})", encoding="utf-8")
    (artifact_dir / "example_faq.md").write_text(FAQ_MD, encoding="utf-8")
    (artifact_dir / "zhihu_example.md").write_text("知乎草稿", encoding="utf-8")
    (artifact_dir / "medium_example.md").write_text("Medium draft", encoding="utf-8")
    (artifact_dir / "page_snapshot.json").write_text('{"url": "x"}', encoding="utf-8")
    return str(artifact_dir)


class TestBilingualZip:
    def test_bundle_task_uses_bilingual_layout(self, tmp_path):
        artifact_dir = tmp_path / "task-1"
        zip_path = bundle_task("task-1", _fill_artifact_dir(artifact_dir),
                              "https://example.com")
        with zipfile.ZipFile(zip_path) as zf:
            names = set(zf.namelist())
            readme = zf.read("README.md").decode("utf-8")

        for expected in (
            "zh/geo_analysis_report.md", "en/geo_analysis_report.md",
            "zh/geo_analysis_report.pdf", "en/geo_analysis_report.pdf",
            "zh/schema.jsonld.html", "en/schema.jsonld.html",
            f"zh/plan_items/{ITEM_STEM}.md", f"en/plan_items/{ITEM_STEM}.md",
            "zh/faq.md", "en/faq.md",
            "zh/zhihu_example.md", "en/medium_example.md", "page_snapshot.json",
        ):
            assert expected in names, expected

        # 不产出无法发布的译文稿，包内不残留 .en 扁平名
        assert "en/zhihu_example.md" not in names
        assert "zh/medium_example.md" not in names
        assert "geo_analysis_report.en.md" not in names

        assert "目录结构" in readme and "Suggested order" in readme
        assert "https://example.com" in readme
        assert "- `en/faq.md`" in readme
        assert "统计 / Totals:" in readme

    def test_english_side_is_monolingual(self, tmp_path):
        zip_path = bundle_task("task-2", _fill_artifact_dir(tmp_path / "task-2"))
        with zipfile.ZipFile(zip_path) as zf:
            en_report = zf.read("en/geo_analysis_report.md").decode("utf-8")
            en_faq = zf.read("en/faq.md").decode("utf-8")
            zh_faq = zf.read("zh/faq.md").decode("utf-8")
        assert not CJK_RE.search(en_report)
        assert not CJK_RE.search(en_faq)
        assert CJK_RE.search(zh_faq)


def _seed_items(app, task_id: str, legacy_first: bool = False) -> list[dict]:
    """生成 13 个条目并返回 {id, stem}；legacy_first 清空首条英文稿。"""
    with app.app_context():
        admin = User.query.filter_by(username="admin").first()
        db.session.add(EvalTask(id=task_id, user_id=admin.id,
                                 target_url="https://example.com", overall_score=30.0))
        db.session.commit()
        items = generator.generate_for_task(
            task_id, {"llm": {}}, {"overall_score": 30.0})
        if legacy_first:
            # 模拟旧生成器产物：中英合稿存在 content，content_en 为空
            items[0].content = (items[0].content + "\n\n## English Part\n\n"
                                + (items[0].content_en or ""))
            items[0].content_en = ""
            db.session.commit()
        return [{"id": i.id, "stem": f"{i.priority}_{i.code}", "code": i.code}
                for i in items]


class TestPlanBundleRoute:
    def test_download_is_bilingual_with_readme(self, app, admin_login):
        _seed_items(app, "bi-1")
        resp = admin_login.get("/plan/bi-1/download")
        assert resp.status_code == 200
        with zipfile.ZipFile(io.BytesIO(resp.data)) as zf:
            names = zf.namelist()
            readme = zf.read("README.md").decode("utf-8")
        zh_items = [n for n in names if n.startswith("zh/plan_items/")]
        en_items = [n for n in names if n.startswith("en/plan_items/")]
        assert len(zh_items) == 13 and len(en_items) == 13
        assert all(n.endswith(".md") for n in zh_items + en_items)
        assert "README.md" in names and "目录结构" in readme

    def test_legacy_item_without_english_falls_back(self, app, admin_login):
        """历史条目（content_en 为空）不产生 en 副本，中文合稿不丢失。"""
        metas = _seed_items(app, "bi-legacy", legacy_first=True)
        legacy_stem = metas[0]["stem"]
        with zipfile.ZipFile(io.BytesIO(
                admin_login.get("/plan/bi-legacy/download").data)) as zf:
            names = zf.namelist()
            combined = zf.read(f"zh/plan_items/{legacy_stem}.md").decode("utf-8")
        assert len([n for n in names if n.startswith("zh/plan_items/")]) == 13
        assert len([n for n in names if n.startswith("en/plan_items/")]) == 12
        assert f"en/plan_items/{legacy_stem}.md" not in names
        assert "验收标准" in combined and "Acceptance" in combined

    def test_reports_and_artifacts_are_sided(self, app, admin_login, tmp_path):
        """磁盘中英报告按语言进 zh/ en/，产出物随规格语言归档。"""
        metas = _seed_items(app, "bi-2")
        with app.app_context():
            task = db.session.get(EvalTask, "bi-2")
            task.artifact_dir = _fill_artifact_dir(tmp_path / "bi-2")
            admin = User.query.filter_by(username="admin").first()
            db.session.add(PlanArtifact(item_id=metas[0]["id"], task_id="bi-2",
                                        user_id=admin.id, kind="zhihu_article",
                                        filename="zhihu_article.md",
                                        content="知乎草稿", source="llm"))
            db.session.add(PlanArtifact(item_id=metas[0]["id"], task_id="bi-2",
                                        user_id=admin.id, kind="sitemap_xml",
                                        filename="sitemap.xml",
                                        content="<urlset/>", source="rule"))
            db.session.commit()

        with zipfile.ZipFile(io.BytesIO(
                admin_login.get("/plan/bi-2/download").data)) as zf:
            names = set(zf.namelist())
        assert "zh/geo_analysis_report.md" in names
        assert "en/geo_analysis_report.md" in names
        assert "geo_analysis_report.en.md" not in names
        assert "zh/artifacts/zhihu_article.md" in names
        assert "artifacts/sitemap.xml" in names   # 规则类产出物不带语言前缀
        assert "report/geo_analysis_report.md" not in names   # 旧 report/ 目录已取消

    def test_item_download_lang(self, app, admin_login):
        item_id = _seed_items(app, "bi-3")[0]["id"]
        zh_body = admin_login.get(f"/plan/item/{item_id}/download").data.decode()
        en_resp = admin_login.get(f"/plan/item/{item_id}/download?lang=en")
        en_body = en_resp.data.decode()

        assert CJK_RE.search(zh_body) and not CJK_RE.search(en_body)
        assert ".en.md" in en_resp.headers["Content-Disposition"]

    def test_edit_page_shows_both_languages(self, app, admin_login):
        """编辑页同时给出中文与英文正文框，并提供英文下载入口。"""
        item_id = _seed_items(app, "bi-4")[0]["id"]
        html = admin_login.get(f"/plan/item/{item_id}").data.decode()
        assert 'name="content"' in html and 'name="content_en"' in html
        assert "lang=en" in html
